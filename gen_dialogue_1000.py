# ---------- 模板变体（程序化扩充）----------
def variants(q, cat):
    """对种子问题生成语气/场景变体，返回列表（去重、排除原句）。"""
    vs = set()
    tpl = {
        "知识问答": ["{q}", "请问，{q}", "{q}？", "我想知道{q}", "{q}呀", "那个，{q}", "爸爸，{q}"],
        "生活常识": ["{q}", "为什么{q}？", "{q}呀", "我一直想问{q}", "{q}是怎么一回事", "{q}呢"],
        "日常闲聊": ["{q}", "{q}呀", "{q}～", "诶，{q}", "说起来，{q}", "{q}嘛"],
        "情感表达": ["{q}", "{q}。", "{q}…", "呜呜{q}", "唉，{q}", "{q}真的", "我今天{q}"],
        "诚实边界": ["{q}", "{q}？", "那{q}", "对了，{q}", "{q}呀"],
        "条件判断": ["{q}", "{q}？", "你觉得{q}", "{q}呢", "那你说{q}"],
        "编程语言": ["{q}", "{q}？", "我想问{q}", "{q}怎么理解", "{q}呀"],
        "协议认知": ["{q}", "{q}？", "{q}是什么意思", "{q}怎么理解"],
        "意见请求": ["{q}", "{q}？", "我想听听你的意见，{q}", "你觉得{q}", "{q}好么"],
        "场景对话": ["{q}", "{q}。", "{q}怎么办", "诶，{q}", "{q}啊"],
    }
    for t in tpl.get(cat, ["{q}"]):
        vs.add(t.format(q=q))
    vs.discard(q)
    return list(vs)

# ---------- 组装 1000 条 ----------
total_target = 1000
questions = []  # (cat, q, keys, objective)
# 先放全部种子
for cat, seeds in SEEDS.items():
    for q, keys, obj in seeds:
        questions.append((cat, q, keys, obj))

# 变体补齐
need = total_target - len(questions)
variants_pool = []
for cat, seeds in SEEDS.items():
    for q, keys, obj in seeds:
        for v in variants(q, cat):
            variants_pool.append((cat, v, keys, obj))
random.shuffle(variants_pool)
# 去重（按问题文本）
seen_q = {q for _, q, _, _ in questions}
added = 0
for item in variants_pool:
    if added >= need:
        break
    cat, q, keys, obj = item
    if q in seen_q:
        continue
    seen_q.add(q)
    questions.append(item)
    added += 1

# 若还不够，继续二次变体（组合变体前缀）
if len(questions) < total_target:
    more = total_target - len(questions)
    combos = []
    for cat, q, keys, obj in questions[:200]:
        for v in variants(q, cat):
            for v2 in variants(v, cat):
                combos.append((cat, v2, keys, obj))
    random.shuffle(combos)
    for item in combos:
        if more <= 0:
            break
        cat, q, keys, obj = item
        if q in seen_q:
            continue
        seen_q.add(q)
        questions.append(item)
        more -= 1

questions = questions[:total_target]
print(f"生成 {len(questions)} 条")

# 类别统计
from collections import Counter
cat_cnt = Counter(c for _, c in [ (q, c) for c, q, k, o in questions])
for c, n in sorted(cat_cnt.items()):
    print(f"  {c}: {n}")

# 客观题（有关键词）比例
obj_n = sum(1 for _, _, k, o in questions if o)
print(f"客观题(关键词可评分): {obj_n} | 主观题(通路匹配): {len(questions)-obj_n}")

# 存 json
