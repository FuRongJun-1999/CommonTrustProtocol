# -*- coding: utf-8 -*-
"""补 v5 剩余变体。"""
def patch(path):
    src = open(path, encoding="utf-8").read()
    pairs = [
        # AI创作版权：创作者保护/AI时代保护自己
        ('"AI创作", "AI作品", "AI画画"],',
         '"AI创作", "AI作品", "AI画画",\n                "保护自己", "AI时代", "创作者"],'),
        # 算法偏见：算法比人更客观/不用怀疑
        ('"算法歧视", "AI偏见"],',
         '"算法歧视", "AI偏见",\n                "比人更客观", "不用怀疑", "算法是不是"],'),
        # 远程办公：又爱又恨/迟早回办公室
        ('"线上办公", "远程工作", "居家工作"],',
         '"线上办公", "远程工作", "居家工作",\n                "又爱又恨", "迟早回办公室", "远程为什么"],'),
        # 生育成本：养一个孩子/花多少钱
        ('"育儿成本", "生孩子"],',
         '"育儿成本", "生孩子",\n                "养一个孩子", "花多少钱", "养孩子"],'),
        # 外卖健康：外卖族自救
        ('"外卖党", "吃外卖"],',
         '"外卖党", "吃外卖",\n                "外卖族", "自救", "外卖怎么吃"],'),
        # 网课效果：便宜又方便/不是更好
        ('"网课自律"],',
         '"网课自律",\n                "便宜又方便", "不是更好", "网课方便"],'),
        # 生育：生不生到底听谁的
        ('"不想生", "催生", "育儿成本", "生孩子"],',
         '"不想生", "催生", "育儿成本", "生孩子",\n                "到底该听谁的", "生不生到底", "该听谁的"],'),
    ]
    for old, new in pairs:
        if old in src:
            src = src.replace(old, new, 1)
        else:
            print(f"跳过（未找到）: {old[:30]}")
    open(path, "w", encoding="utf-8").write(src)
    print("patched")

