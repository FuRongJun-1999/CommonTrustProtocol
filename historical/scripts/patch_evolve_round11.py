def main():
    src = open(TRANSLATE_PY, encoding="utf-8").read()

    # 1) DOMAIN_SYNONYM_CLUSTERS 追加（在 "静电" 簇之后插入）
    anchor = '        "注意机制": ["注意机制", "选择性注意", "分散注意", "什么是注意机制"],'
    assert anchor in src, "找不到 注意机制 簇锚点"
    add_clusters = ""
    for theme, triggers, _ans, _route in NEW_THEMES:
        add_clusters += '        "%s": [%s],\n' % (
            theme, ", ".join('"%s"' % t for t in triggers))
    src = src.replace(anchor, anchor + "\n" + add_clusters.rstrip("\n"))

    # 2) DOMAIN_ROUTE 追加（在 "自我认知" 路由之后插入）
    route_anchor = '    "价值观": "价值理论与AI对齐", "好奇心": "智能论", "自我认知": "自我意识",'
    assert route_anchor in src, "找不到 DOMAIN_ROUTE 锚点"
    add_routes = "".join('    "%s": "%s",\n' % (t, r) for t, _tr, _ans, r in NEW_THEMES)
    src = src.replace(route_anchor, route_anchor + "\n" + add_routes.rstrip("\n"))

    # 3) REVERSE_DAILY 直答追加（在 "静电" 直答之后插入）
    ans_anchor = '    "静电": "为什么冬天脱毛衣会噼啪响'
    assert ans_anchor in src, "找不到 静电 直答锚点"
    # 在静电直答整行后插入——静电行以"（别慌）"结尾
    st_ans_end = "（别慌）\","
    idx = src.index(ans_anchor)
    end_idx = src.index(st_ans_end, idx) + len(st_ans_end)
    add_ans = ""
    for theme, _tr, ans, _route in NEW_THEMES:
        add_ans += '\n    "%s": "%s",' % (theme, ans)
    src = src[:end_idx] + add_ans + src[end_idx:]

    open(TRANSLATE_PY, "w", encoding="utf-8").write(src)
    print("已写入 3 个新主题（簇+路由+直答）: %s" % ", ".join(t for t, *_ in NEW_THEMES))

    # 4) 语法验证
    import py_compile
    py_compile.compile(TRANSLATE_PY, doraise=True)
    print("语法 OK")

if __name__ == "__main__":
    main()
