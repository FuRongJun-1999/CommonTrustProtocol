# -*- coding: utf-8 -*-
"""补 v4 最后 7 个变体。"""
def patch(path):
    src = open(path, encoding="utf-8").read()
    pairs = [
        # 留守儿童：不出去打工/家里怎么生活
        ('"打工和孩子", "孩子缺陪伴"],',
         '"打工和孩子", "孩子缺陪伴",\n                "不出去打工", "家里怎么生活", "打工挣钱"],'),
        # 游戏成瘾：分清娱乐和沉迷
        ('"网瘾", "游戏上瘾", "打游戏", "孩子玩游戏"],',
         '"网瘾", "游戏上瘾", "打游戏", "孩子玩游戏",\n                "分清娱乐和沉迷", "娱乐和沉迷"],'),
        # 直播消费：真的便宜吗
        ('"直播电商", "直播间", "主播"],',
         '"直播电商", "直播间", "主播",\n                "真的便宜", "直播的东西"],'),
        # 数据隐私：被谁拿走/归谁
        ('"大数据杀熟", "隐私", "数据安全"],',
         '"大数据杀熟", "隐私", "数据安全",\n                "被谁拿走", "数据归谁", "平台还是用户"],'),
        # 养老社会：老了谁来照顾/我们这一代
        ('"养老靠谁", "退休金"],',
         '"养老靠谁", "退休金",\n                "谁来照顾", "我们这一代", "老了以后"],'),
        # 城乡流动：打工多年/没归属感
        ('"北漂", "打工人", "农民工", "落户"],',
         '"北漂", "打工人", "农民工", "落户",\n                "打工多年", "没归属感", "归属感"],'),
    ]
    for old, new in pairs:
        assert old in src, f"未找到: {old[:30]}"
        src = src.replace(old, new, 1)
    open(path, "w", encoding="utf-8").write(src)
    print("patched")

