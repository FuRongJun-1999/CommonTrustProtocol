def classify_condition_space(question: str) -> dict:
    """学科级条件空间识别（CSPRE Step1 · 2026-08-20）。

    问题 → 学科域（条件空间）硬分类：
      1. DOMAIN_ROUTE 规范词命中（翻译表：俗语→规范词→学科域）
      2. QUESTION_DOMAIN_PRIORS 问题关键词命中
      3. 均未命中 → {"domain": None, "confidence": 0, "nav": False}

    返回 {domain, confidence, matched}——domain=None 表示无法分类
    （走全库检索 + 诚实边界，不做定向导航）。
    """
    # 1. 翻译表规范词 → 学科域（DOMAIN_ROUTE 已有，如 沸腾→物理学）
    route_hits = []
    try:
        fp = encode(question)
        for term, dom in DOMAIN_ROUTE.items():
            if term in fp:
                route_hits.append((dom, fp.get(term, 1.0)))
    except Exception:
        route_hits = []
    # 1.5 歧义词前置消解（v1.18 · 2026-08-20 荣：数学/代码域要 100% 路由）：
    # 「函数」在翻译表有 编程函数(→编程语言) 和 函数定义(→数学) 两个条目，
    # 「什么是函数？」encode 命中「编程函数」→ 误路由编程。纯定义询问
    # （什么是函数/函数是什么/什么叫函数）在无编程特征词时 → 数学优先，
    # 覆盖翻译表命中（数学定义是默认义，编程是特化义需显式特征词）。
    _PROG_HINT = ("呀", "呢", "怎么理解", "编程里", "编程中的", "代码", "程序",
                  "for", "while", "循环语句", "语法", "变量声明", "函数调用",
                  "参数", "返回值", "Python", "JS", "Java", "C++", "函数和",
                  "和变量的区别", "区别", "和循环")
    if ("函数" in question and not any(h in question for h in _PROG_HINT)
            and any(k in question for k in ("什么是函数", "函数是什么", "什么叫函数"))):
        route_hits = [(dom, w) for dom, w in route_hits if dom != "编程语言"]
        route_hits.append(("数学", 2.0))
    # 2. 问题关键词先验 → 学科域
    prior_hits = []
    for dom, kws in QUESTION_DOMAIN_PRIORS.items():
        hit_kws = [k for k in kws if k in question]
        if hit_kws:
            prior_hits.append((dom, len(hit_kws)))
    # 合并：翻译表命中优先（确定性），先验补充
    best = None
    if route_hits:
        # 多命中取最高权重
        from collections import Counter
        dom_score = Counter()
        for dom, w in route_hits:
            dom_score[dom] += w
        top_dom, top_w = dom_score.most_common(1)[0]
        best = {"domain": top_dom, "confidence": min(1.0, 0.6 + 0.1 * top_w),
                "matched": [d for d, _ in route_hits], "nav": True}
    elif prior_hits:
        prior_hits.sort(key=lambda x: -x[1])
        top_dom, n = prior_hits[0]
        best = {"domain": top_dom,
                "confidence": min(1.0, 0.5 + 0.1 * n),
                "matched": [d for d, _ in prior_hits], "nav": True}
    if best is None:
        return {"domain": None, "confidence": 0.0, "matched": [],
                "nav": False}
    return best


def _domain_matches(domain_filter: str, node_domain: str) -> bool:
    """学科域匹配（宽松）：「数学」匹配「初中数学/高中数学/数学分析…」。
    去「学」后缀双向包含（与 v1.16 先验校正一致）。"""
    if not domain_filter or not node_domain:
        return True
    dm = domain_filter.rstrip("学")
    return bool(dm and (dm in node_domain or node_domain in dm))


# 通用疑问词/虚词（第二层条目导航用：不参与焦点词提取）
_FOCUS_STOP = ("什么", "怎么", "为什么", "多少", "哪些", "哪个", "如何", "是",
               "的", "了", "吗", "呢", "啊", "呀", "吧", "求", "公式", "内容",
               "定义", "解释", "请", "给", "一下", "分别", "之间的", "关系")


def _extract_focus_words(question: str) -> list:
    """提取问题焦点词（第二层条目导航）：问题实义词（≥2字窗口），
    用于校验 direct_answer 是否回应问题（子条件分析）。

    「三角形的内角和是多少度？」→ 焦点词含「内角」「三角形」
    「一元二次方程求根公式」→ 「求根」「方程」
    空 → 不干预（保守：无法提取焦点时不做条目降权）
    """
    if not question:
        return []
    try:
        import re as _re
        chars = [c for c in question if "\u4e00" <= c <= "\u9fff"]
        focus = set()
        # 4字/3字窗口（实义词），跳过含疑问词的窗口
        for L in (4, 3):
            for i in range(len(chars) - L + 1):
                w = "".join(chars[i:i + L])
                if any(s in w for s in _FOCUS_STOP):
                    continue
                focus.add(w)
        # 2字窗口补（「内角」「求根」）
        for i in range(len(chars) - 1):
            w = "".join(chars[i:i + 2])
            if w not in ("是什么", "多少", "怎么", "为什么", "公式", "内容",
                         "定义", "关系", "分别", "之间", "一下", "多少度"):
                focus.add(w)
        # 长度优先排序（更长的焦点词更精确）
        return sorted(focus, key=lambda x: -len(x))[:8]
    except Exception:
        return []


def _extract_tail_focus(question: str) -> list:
    """提取问题【尾部焦点词】（v1.19 第二层条目导航核心）：

    答案焦点通常在句尾实义词——「内角和是多少度」→「内角和」、
    「求根公式」→「求根」、「通项公式」→「通项」。题干主语
    （三角形/方程/水）不算焦点（面积条目也含「三角形」但非答案焦点）。

    从问题末尾往前扫，找第一个未被疑问词污染的 ≥2 字实义词。
    返回列表（可能多个），空 → 不干预。
    """
    if not question:
        return []
    try:
        import re as _re
        # 去标点/数字，保留中文
        text = _re.sub(r"[^\u4e00-\u9fff]", "", question)
        if not text:
            return []
        focus = set()
        # 从末尾往前：取最后 8 字符窗口，优先末位实义词
        # （「求根公式」→求根；「通项公式」→通项——公式是后缀词，
        #  实义词在公式前）。跳过疑问词/泛词。
        tail = text[-8:]
        for L in (4, 3, 2):
            for i in range(len(tail) - L + 1):
                w = tail[i:i + L]
                if any(s in w for s in ("是什么", "多少", "怎么", "为什么",
                                        "多少度", "是多少", "等于")):
                    continue
                # 「X公式/X定义/X内容」→ 取 X（公式前的实义词）
                if w.endswith(("公式", "定义", "内容")):
                    w = w[:-2]
                if len(w) < 2:
                    continue
                if w in ("三角形", "方程", "水的", "一个", "什么", "的", "是"):
                    continue
                focus.add(w)
        # 优先长词（更精确），最多返回 3 个
        return sorted(focus, key=lambda x: -len(x))[:3]
    except Exception:
        return []


def graph_retrieve(dex, question, limit=10):
    """知识整体图谱检索（普通人日常话 → 学科知识卡）。

    四路融合（对齐灵枢语义空间三层架构）：
      快速层（dex_respond，全库扫描）：
        1) 语义指纹命中（翻译表：俗语→规范词）
        2) 学科路由 × 教育层级加权
        3) 二元组命中 + 语义坐标余弦
      神经层（索引独立召回，不依赖快速层）：
        4) bge-small-zh 余弦（水烧开→沸腾、单字学科词「熵」这类真正语义）
    合并：快速层 top-15 ∪ 神经层 top-10 → 统一融合分排序。
    """
    # 快速层：三路评分取 top-15
    fast = dex.dex_respond(question, limit=15, translator=__import__(__name__))
    # 神经层：索引独立召回（单字学科词/俗语等快速层漏检的语义）
    neural_map = {}
    neural_names = []
    try:
        from neural_retrieve import NeuralRetriever
        nr = NeuralRetriever()
        idx_hits = nr.search_index(question, limit=10, threshold=0.3)
        neural_map = {name: score for name, score, _d, _e in idx_hits}
        neural_names = [name for name, _s, _d, _e in idx_hits]
    except Exception:
        neural_map = {}
        idx_hits = []
        neural_names = []
    # 合并候选：快速层 + 神经层独有卡
    if not fast and not neural_names:
        return []
    merged = list(fast)
    fast_names = {h['name'] for h in fast}
    neural_info = {name: (dom, edu) for name, _s, dom, edu in idx_hits}
    for name in neural_names:
        if name not in fast_names:
            dom, edu = neural_info.get(name, (None, None))
            merged.append({"name": name, "score": 0.0, "matched": ["语义"],
                           "neural_score": neural_map[name],
                           "domain": dom, "edu_level": edu})
    # 融合分：快速层为主、神经层微调（v1.16）
    # 之前 min(score,1.0) 把快速层高分全压平（初中物理 7.76 和固体物理 2.11
    # 都变 1.0），区分度丢失 → bge 神经分（字面相似，会把「沸腾」错配到
    # 固体物理）反超决胜。改为按快速分强弱分段：
    #   fast_abs = s/(1+s)   soft 压缩保留区分度（7.76→0.886, 2.11→0.678）
    #   强命中（≥0.8：翻译表/学科路由直中）：0.75×fast + 0.25×neural
    #     翻译命中=日常话→规范词的确定性翻译，比 bge 模糊相似可靠，应为主
    #   弱命中（>0 且 <0.8：纯字面/二元组噪声）：0.3×fast + 0.7×neural
    #     字面分低置信，神经分才是真语义（「1+1」→小学数学 fast 仅 0.03，
    #     神经 0.616——若按强命中通道会把小学数学拖输给线性代数）
    #   神经层独有卡：0.4×neural（快速层空转时才生效，权重降低防噪声反超）
    # v1.16 修复（2026-08-19）：神经层高置信（≥0.6）时优先——
    # 「圆的周长」快速层错配初中地理 2.04（强命中 0.503）压过神经层
    # 正确「圆的周长与面积」0.703（0.281）。语义层高置信应盖过快
    # 速层字面噪声（错误卡靠学科路由硬加权拿高分）。
    # v1.17 修复（2026-08-19 白箱边界测试 52 例检索噪声）：
    #  ①神经层独有卡（不在快速层 top）也享受 0.85×neural 优先——
    #    之前只在 fast_raw<0.8 时走此通道，「概率基本性质→概率论卡」
    #    神经 0.654 却因不在快速层按 0.4×0.654=0.262 计分，被快速层
    #    噪声「小学英语 3.78」压过 → 答成动物词汇。
    #  ②快速层字面高分 + 神经低分（<0.35，语义不匹配）降权——
