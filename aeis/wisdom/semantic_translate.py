def _extract_focus_words(question: str) -> list:
    """提取问题焦点词（第二层条目导航）：问题实义词（≥2字窗口），
    用于校验 direct_answer 是否回应问题（子条件分析）。

    「三角形的内角和是多少度？」→ 焦点词含「内角」「三角形」
    「一元二次方程求根公式」→ 「求根」「方程」
    空 → 不干预（保守：无法提取焦点时不做条目降权）
    """
    if not question:
        return []
    try:
        import re as _re
        chars = [c for c in question if "\u4e00" <= c <= "\u9fff"]
        focus = set()
        # 4字/3字窗口（实义词），跳过含疑问词的窗口
        for L in (4, 3):
            for i in range(len(chars) - L + 1):
                w = "".join(chars[i:i + L])
                if any(s in w for s in _FOCUS_STOP):
                    continue
                focus.add(w)
        # 2字窗口补（「内角」「求根」）
        for i in range(len(chars) - 1):
            w = "".join(chars[i:i + 2])
            if w not in ("是什么", "多少", "怎么", "为什么", "公式", "内容",
                         "定义", "关系", "分别", "之间", "一下", "多少度"):
                focus.add(w)
        # 长度优先排序（更长的焦点词更精确）
        return sorted(focus, key=lambda x: -len(x))[:8]
    except Exception:
        return []


def _extract_tail_focus(question: str) -> list:
    """提取问题【尾部焦点词】（v1.19 第二层条目导航核心）：

    答案焦点通常在句尾实义词——「内角和是多少度」→「内角和」、
    「求根公式」→「求根」、「通项公式」→「通项」。题干主语
    （三角形/方程/水）不算焦点（面积条目也含「三角形」但非答案焦点）。

    从问题末尾往前扫，找第一个未被疑问词污染的 ≥2 字实义词。
    返回列表（可能多个），空 → 不干预。
    """
    if not question:
        return []
    try:
        import re as _re
        # 去标点/数字，保留中文
        text = _re.sub(r"[^\u4e00-\u9fff]", "", question)
        if not text:
            return []
        focus = set()
        # 从末尾往前：取最后 8 字符窗口，优先末位实义词
        # （「求根公式」→求根；「通项公式」→通项——公式是后缀词，
        #  实义词在公式前）。跳过疑问词/泛词。
        tail = text[-8:]
        for L in (4, 3, 2):
            for i in range(len(tail) - L + 1):
                w = tail[i:i + L]
                # 含疑问词/结构词的窗口丢弃（碎片「公式是/是什/什么是」不是焦点）
                if any(s in w for s in ("什么", "多少", "怎么", "为什么",
                                        "多少度", "是多少", "等于", "公式是",
                                        "是什", "的什么", "一个", "是", "么")):
                    continue
                # 「X公式/X定义/X内容」→ 取 X（公式前的实义词）
                if w.endswith(("公式", "定义", "内容")):
                    w = w[:-2]
                if len(w) < 2:
                    continue
                if w in ("三角形", "方程", "水的", "一个", "的", "是"):
                    continue
                focus.add(w)
        # 优先长词（更精确），最多返回 3 个
        return sorted(focus, key=lambda x: -len(x))[:3]
    except Exception:
        return []


def graph_retrieve(dex, question, limit=10):
    """知识整体图谱检索（普通人日常话 → 学科知识卡）。

    四路融合（对齐灵枢语义空间三层架构）：
      快速层（dex_respond，全库扫描）：
        1) 语义指纹命中（翻译表：俗语→规范词）
        2) 学科路由 × 教育层级加权
        3) 二元组命中 + 语义坐标余弦
      神经层（索引独立召回，不依赖快速层）：
        4) bge-small-zh 余弦（水烧开→沸腾、单字学科词「熵」这类真正语义）
    合并：快速层 top-15 ∪ 神经层 top-10 → 统一融合分排序。
    """
    # 快速层：三路评分取 top-15
    fast = dex.dex_respond(question, limit=15, translator=__import__(__name__))
    # 神经层：索引独立召回（单字学科词/俗语等快速层漏检的语义）
    neural_map = {}
    neural_names = []
    try:
        from neural_retrieve import NeuralRetriever
        nr = NeuralRetriever()
        idx_hits = nr.search_index(question, limit=10, threshold=0.3)
        neural_map = {name: score for name, score, _d, _e in idx_hits}
        neural_names = [name for name, _s, _d, _e in idx_hits]
    except Exception:
        neural_map = {}
        idx_hits = []
        neural_names = []
    # 合并候选：快速层 + 神经层独有卡
    if not fast and not neural_names:
        return []
    merged = list(fast)
    fast_names = {h['name'] for h in fast}
    neural_info = {name: (dom, edu) for name, _s, dom, edu in idx_hits}
    for name in neural_names:
        if name not in fast_names:
            dom, edu = neural_info.get(name, (None, None))
            merged.append({"name": name, "score": 0.0, "matched": ["语义"],
                           "neural_score": neural_map[name],
                           "domain": dom, "edu_level": edu})
    # 融合分：快速层为主、神经层微调（v1.16）
    # 之前 min(score,1.0) 把快速层高分全压平（初中物理 7.76 和固体物理 2.11
    # 都变 1.0），区分度丢失 → bge 神经分（字面相似，会把「沸腾」错配到
    # 固体物理）反超决胜。改为按快速分强弱分段：
    #   fast_abs = s/(1+s)   soft 压缩保留区分度（7.76→0.886, 2.11→0.678）
    #   强命中（≥0.8：翻译表/学科路由直中）：0.75×fast + 0.25×neural
    #     翻译命中=日常话→规范词的确定性翻译，比 bge 模糊相似可靠，应为主
    #   弱命中（>0 且 <0.8：纯字面/二元组噪声）：0.3×fast + 0.7×neural
    #     字面分低置信，神经分才是真语义（「1+1」→小学数学 fast 仅 0.03，
    #     神经 0.616——若按强命中通道会把小学数学拖输给线性代数）
    #   神经层独有卡：0.4×neural（快速层空转时才生效，权重降低防噪声反超）
    # v1.16 修复（2026-08-19）：神经层高置信（≥0.6）时优先——
    # 「圆的周长」快速层错配初中地理 2.04（强命中 0.503）压过神经层
    # 正确「圆的周长与面积」0.703（0.281）。语义层高置信应盖过快
    # 速层字面噪声（错误卡靠学科路由硬加权拿高分）。
    # v1.17 修复（2026-08-19 白箱边界测试 52 例检索噪声）：
    #  ①神经层独有卡（不在快速层 top）也享受 0.85×neural 优先——
    #    之前只在 fast_raw<0.8 时走此通道，「概率基本性质→概率论卡」
    #    神经 0.654 却因不在快速层按 0.4×0.654=0.262 计分，被快速层
    #    噪声「小学英语 3.78」压过 → 答成动物词汇。
    #  ②快速层字面高分 + 神经低分（<0.35，语义不匹配）降权——
    #    「质数→质量」「概率→小学英语」靠二元组/学科路由硬加权拿高分，
    #    bge 语义分低证明不相关 → 0.55×fast_abs 而非 0.75×。
    for h in merged:
        name = h['name']
        neural = neural_map.get(name, 0.0)
        h['neural_score'] = round(neural, 3)
        fast_raw = h.get('score', 0.0) or 0.0
        if neural >= 0.6:
            # 神经层高置信（语义真命中）→ 语义优先（含神经层独有卡）
            h['score'] = round(0.85 * neural + 0.15 * fast_raw / (1.0 + fast_raw), 3)
        elif fast_raw >= 0.8:
            fast_abs = fast_raw / (1.0 + fast_raw)
            if neural < 0.35:
                # 字面高分但语义低 → 检索噪声，降权
                h['score'] = round(0.55 * fast_abs + 0.1 * neural, 3)
            else:
                h['score'] = round(0.75 * fast_abs + 0.25 * neural, 3)
        elif fast_raw > 0:
            fast_abs = fast_raw / (1.0 + fast_raw)
            h['score'] = round(0.3 * fast_abs + 0.7 * neural, 3)
        else:
            h['score'] = round(0.4 * neural, 3)
    merged.sort(key=lambda x: -x['score'])
    # 神经层学科先验校正（v1.16）：bge 字面相似会错排学科
    # （「铁球羽毛」→初中地理、「光的反射定律」→初中生物神经反射）。
    # 问题关键词命中学科域先验 → 命中域卡 ×1.25、其余 ×0.75，再排序。
    # v1.16 修复：fp 非空时也评估（「反射定律」fp 含反射词，但物理先验仍需压生物）
    try:
        fp_keys = set(encode(question).keys())
    except Exception:
        fp_keys = set()
    prior_doms = set()
    for _dom, _kws in QUESTION_DOMAIN_PRIORS.items():
        if any(_kw in question for _kw in _kws):
            prior_doms.add(_dom)
    if prior_doms:
        for h in merged:
            hdom = h.get("domain") or ""
            # v1.16 修复：宽松匹配——「物理学」先验要覆盖「初中物理/高中物理」
            # （学科卡 domain 带学段前缀）；_dm 去「学」后缀（物理学→物理）
            hit = False
            for _d in prior_doms:
                _dm = _d.rstrip("学")
                if _dm and (_dm in hdom or hdom in _dm):
                    hit = True
                    break
            if hit:
                h['score'] = round(min(1.0, h['score'] * 1.25), 3)
            else:
                h['score'] = round(h['score'] * 0.75, 3)
        # v1.17 编程歧义强路由（2026-08-19 三类专项测试）：
        # fp 命中「编程函数/编程循环/编程变量」等强翻译词时，编程域卡
        # 语义确定（翻译表直译），但神经层候选缺失（bge 把「函数」匹配到
        # 数学函数）→ neural=0 被 v1.17 降权压制，仍输给数学卡。
        # 翻译命中=确定性语义，直接再加 0.15 分（压过数学卡，且不误伤
        # 其他——仅 fp 含编程歧义词时触发）。
        _prog_fp = any(k in fp_keys for k in
                       ("编程函数", "编程循环", "编程变量", "数组",
                        "编程类", "调试", "Python", "Rust", "TypeScript"))
        if _prog_fp:
            for h in merged:
                if "编程语言" in (h.get("domain") or ""):
                    h['score'] = round(min(1.0, h['score'] + 0.15), 3)
        merged.sort(key=lambda x: -x['score'])
    # 递归检索（v1.16 P1 接口升级）：top 卡附 direct_answer（直接答案）。
    # 优先级：卡内条目递归（交集≥3 的实义条目）> REVERSE_DAILY（焦点词修正）。
    # 「具体问题做一个递归检索」——第一层定位卡已在上，这里是第二层。
    # v1.21 修复（2026-08-20 荣：T2 检索错配）：循环原只处理 merged[:3]，
    # 但 CSPRE/尾焦点排序后 top3 会变——「1+1等于几」循环处理的是数学/
    # 初中数学/高中数学，返回 top 却是小学数学知识点内容（循环时排第4，
    # 未被处理 → direct_answer=None → 白箱无答案可答）。改为处理全部
    # merged（~20 卡，SQL 查询开销可接受），保证任何最终 top 都有 direct。
    try:
        fp_q = encode(question)
        for h in merged:
            # v1.16 修复（2026-08-19）：神经层条目（node_subject_xxx·知识点名）
            # 是知识点节点——直接从知识点内容取答案，不走卡名递归
            # （卡名递归查不到 node_subject 前缀的知识点节点 → ans=None）。
            _nm = h.get("name", "")
            if _nm.startswith(("node_subject_", "node_stage_")):
                # 从「卡前缀·知识点名」定位知识点节点（kp_xxx + card:<前缀> 标签）
                _parts = _nm.split("·")
                _card_prefix = _parts[0]
                _kp_name = _parts[-1] if len(_parts) > 1 else _nm
                _row = None
                try:
                    _row = dex.store.conn.execute(
                        "SELECT content FROM nodes WHERE tags LIKE ? AND tags LIKE ? "
                        "AND state_attributes LIKE ? LIMIT 1",
                        ('%knowledge_point%', '%card:' + _card_prefix + '%',
                         '%"name": "' + _kp_name + '"%')).fetchone()
                except Exception:
                    _row = None
                if _row and _row[0]:
                    _c = _row[0].strip()
                    # 智能截断（160 字符内分号边界）
                    _cut = 160
                    if len(_c) > _cut:
                        _seg = _c[:_cut]
                        _cut_at = max(_seg.rfind("；"), _seg.rfind("。"),
                                      _seg.rfind("，"), _seg.rfind(";"))
                        _c = _seg[:_cut_at + 1] if _cut_at > 60 else _seg
                    h['direct_answer'] = _c
                    h['name'] = _kp_name  # 规范化显示名
                continue
            # 1) 卡内条目递归（强共现，如「串联电路」→ head 引言即答案）
            _ans, _sc = recursive_item_answer(dex, h.get("name", ""), fp_q, question)
            # 2) REVERSE_DAILY：焦点词（问题中位置最靠后的规范词）的人话答案
            _dterm = _pick_daily_term(fp_q, question)
            # v1.16 白箱条件感知修复：问题含条件变体词（珠峰/高压锅/海拔/气压等）
            # 时不用人话兜底答案（「水烧到咕嘟咕嘟冒大泡」无条件），
            # 走知识点/整卡答案——条件变化必须条件化回答。
            _daily = None
            if _dterm and not any(
                    w in question for w in
                    ("珠峰", "珠穆朗玛", "高原", "山顶", "高压锅", "海拔",
                     "气压", "高压", "低压", "潜水", "太空", "深海")):
                _daily = REVERSE_DAILY.get(_dterm)
            # v1.20 优先级调整（2026-08-20 知识飞轮）：REVERSE_DAILY 直答
            # （翻译表确定性答案：一年12个月/天空蓝瑞利散射）优先于卡内递归
            # （模糊条目匹配可能错配——「一年有多少个月」递归命中「四季」卡）。
            # 日常翻译=确定性语义（俗语→规范词→直答），卡递归是近似检索。
            if _daily:
                h['direct_answer'] = _daily
            elif _ans and _sc >= 3.6:
                h['direct_answer'] = _ans
            # 条件词问题：人话比喻（daily/decode_daily）也会覆盖条件答案，一并清掉
            h['daily'] = _daily
            if _daily is None and any(
                    w in question for w in
                    ("珠峰", "珠穆朗玛", "高原", "山顶", "高压锅", "海拔",
                     "气压", "高压", "低压", "潜水", "太空", "深海")):
                h['matched'] = []
        # v1.16 跨卡精确答案优先：有 direct_answer 的卡排前
        # （「KKT和条件论」→ 约束优化卡的条件论映射知识点 而非 条件论元层卡）
        merged.sort(key=lambda x: (0 if x.get("direct_answer") else 1,
                                   -x.get("score", 0)))
    except Exception as _e:
        import traceback as _tb
        _tb.print_exc()
        pass
    # 补 id（网页端详情/展开用）
    try:
        from aeis.core import MemoryLayer as _ML
        id_by_name = {}
        for _n in dex.store.query_nodes(layer=_ML.KNOWLEDGE, limit=500):
            _sa = _n.state_attributes
            _nm = _sa.get('name')
            if _nm and _nm not in id_by_name:
                id_by_name[_nm] = _n.id
        for h in merged:
            h['id'] = id_by_name.get(h['name'])
    except Exception:
        pass
    # CSPRE 学科级导航（v1.18 · 2026-08-20）：分类命中 → 非目标学科降权
    # （「什么是函数呀」→编程域 → 数学卡 ×0.75，压跨学科噪声；
    #  分类未命中 nav=False → 不干预，走全库+诚实边界）
    try:
        _cs = classify_condition_space(question)
        if _cs.get("nav"):
            _df = _cs["domain"]
            for h in merged:
                hdom = h.get("domain") or ""
                if not _domain_matches(_df, hdom):
                    h['score'] = round(h['score'] * 0.75, 4)
            merged.sort(key=lambda x: -x['score'])
            # 带条件空间声明的返回（白箱可解释）
            for h in merged[:limit]:
                h['cond_space'] = _df
    except Exception:
        pass
    # 第二层条目导航（v1.19 · 2026-08-20 荣：条目错配=递归中的子条件分析
    # 错误——第一层路由到学科域，第二层要路由到条目）。
    # 用问题【尾部焦点词】校验 direct_answer：句尾实义词是答案焦点
    # （「内角和是多少度」→内角和；「求根公式」→求根），题干主语
    # （三角形/方程）不算——面积条目含「三角形」但非答案焦点。
    # 不回应尾焦点的 direct（内角和→面积、求根→一元一次）降权。
    try:
        _tail_focus = _extract_tail_focus(question)
        if _tail_focus:
            for h in merged:
                d = h.get("direct_answer") or ""
                if d and not any(f in d for f in _tail_focus):
                    h['score'] = round(h['score'] * 0.7, 4)
            # 含焦点的卡直接排前（不只降权——避免降权后空 direct 卡上位）
            merged.sort(key=lambda x: (
                0 if (x.get("direct_answer") or "") and any(
                    f in x["direct_answer"] for f in _tail_focus) else 1,
                -x.get("score", 0)))
    except Exception:
        pass
    # 第三层路由（v1.20 · 2026-08-20 荣：对话集——过去有人问过类似问题，
    # 寻路方式是怎样；形成长期记忆/技能；白箱绑定灵枢）。
    # 触发：第一/二层路由结果不佳（top score < 0.5 = 检索弱/可能盲区）
    # 时，查历史经验库（route_memory）：语义相似问题 → 已验证路径补强
    # （荣：不随意切片，在可能的语义中匹配——bge 语义余弦）。
    # 防固化错误：仅取 verified=True 的历史路径；无匹配或未验证 → 不干预。
    try:
        _top_score = merged[0].get("score", 0) if merged else 0
        if _top_score < 0.5:
            from route_memory import RouteMemory
            _rm = RouteMemory()
            _hist = _rm.recall(question, threshold=0.6)
            if _hist:
                _best = _hist[0]
                if _best.get("verified"):
                    # 历史已验证路径 → 把链上卡名加入 merged（提升命中）
                    _hist_names = _best.get("chain", [])
                    for h in merged:
                        if h.get("name") in _hist_names:
                            h['score'] = round(min(1.0, h['score'] + 0.3), 4)
                    merged.sort(key=lambda x: -x['score'])
                    # 记录本次查询（经验库更新——白箱绑定灵枢）
                    try:
                        _rm.record(question,
                                   [h.get("name", "") for h in merged[:3]],
                                   verified=False)  # 本次未经验证，待验证
                    except Exception:
                        pass
    except Exception:
        pass
    _record_chain_heat([h['name'] for h in merged[:3]])
    return merged[:limit]


