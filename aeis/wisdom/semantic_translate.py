def gen_followup(question: str, answer: str = "", limit: int = 2,
                 depth: int = 1) -> list:
    """从答案/问题命中的概念反查前置链 → 生成递归追问候选。

    例：「为什么天空是蓝色的」→ 命中「天空蓝色」→ 前置 [瑞利散射, 波长]
       → 追问候选: [{'q': '什么是瑞利散射？', 'concept': '瑞利散射'}, ...]

    递归 depth>1：前置的前置（波长 → 波 → 振动），生成更深追问。
    返回 [{'q': '...', 'concept': '...'}]，最多 limit 条。
    """
    prereq = _load_prereq()
    if not prereq:
        return []
    try:
        # 1. 从回答内容提取命中的概念（答到了什么 → 它的前置是追问对象）
        concepts = []
        if answer:
            fp_a = encode(answer)
            for t in fp_a:
                if t in prereq:
                    concepts.append(t)
        # 2. 从问题本身提取概念（补充——回答没命中前置链时用问题词）
        if not concepts:
            fp_q = encode(question)
            for t in fp_q:
                if t in prereq:
                    concepts.append(t)
        # 3. 去重 + 沿链递归
        seen = set()
        out = []
        _pending = list(concepts)
        for _d in range(depth):
            _next = []
            for _c in _pending:
                for _p in prereq.get(_c, []):
                    if _p in seen:
                        continue
                    seen.add(_p)
                    out.append({"q": f"什么是{_p}？", "concept": _p})
                    _next.append(_p)
                    if len(out) >= limit:
                        return out
            _pending = _next
        return out
    except Exception:
        return []


