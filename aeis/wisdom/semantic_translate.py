    daily_terms = [t for t in fp if t in REVERSE_DAILY]
    if daily_terms:
        best, best_pos = None, -2
        for term in daily_terms:
            pos = question.rfind(term)
            if pos > best_pos:
                best, best_pos = term, pos
        if best is not None:
            return best
        return max(daily_terms, key=lambda t: (len(t), fp.get(t, 0.0)))
    best, best_pos = None, -2
    for term in fp:
        pos = question.rfind(term)
        if pos < 0:
            continue  # 词未在问题中出现（口语变体）→ 不抢焦点
        if pos > best_pos:
            best, best_pos = term, pos
    if best is not None:
        return best
    # 全部未直接出现 → 取权重最高的长规范词
    return max(fp, key=lambda t: (len(t), fp.get(t, 0.0))) if fp else None


